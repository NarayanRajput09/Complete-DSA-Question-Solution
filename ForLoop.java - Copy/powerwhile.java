
        //  15. Write a program to find the power of a number 
        // Take two inputs. 

import java.util.*;
public class powerwhile { 
       public static void main(String[] args) {
        Scanner sc = new Scanner(System.in);
                
        
        int m=sc.nextInt();
        int n=sc.nextInt();

        int multi =1;
        int i=0;

        while(i<n){
        multi =multi*m;
        }
        System.out.print("multi =" + multi);
        i++;
        }
    }
    



