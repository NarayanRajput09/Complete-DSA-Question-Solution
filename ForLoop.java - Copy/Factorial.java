public class Factorial {
    // Write a program that asks the user to enter a number and then prints the factorial of that number using a loop.

    public static void main(String[] args) {
        int n = 4;
        int fact =1;
        int i=1;
        while(i<=n){

        
         fact =fact*i;
        System.out.println(fact);
        i++;
        }
    }
    
}
